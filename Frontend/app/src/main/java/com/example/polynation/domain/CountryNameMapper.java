    public static String getEnglishNameByRussianName(String russianName) {
        String iso2 = getIso2ByRussianName(russianName);
        if (iso2 == null || iso2.isEmpty()) return null;
        String english = new Locale("", iso2.toUpperCase()).getDisplayCountry(Locale.ENGLISH);

        if (english == null || english.isEmpty() || english.equalsIgnoreCase(iso2)) return null;
        return english;
    }

